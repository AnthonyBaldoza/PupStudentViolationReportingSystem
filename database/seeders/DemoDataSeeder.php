<?php

namespace Database\Seeders;

use App\Exceptions\WorkflowException;
use App\Models\Course;
use App\Models\DisciplinaryAction;
use App\Models\OffenseRule;
use App\Models\Section;
use App\Models\Student;
use App\Models\User;
use App\Models\ViolationCategory;
use App\Services\ViolationWorkflowService;
use Illuminate\Database\Seeder;

/**
 * OPTIONAL demo data:  php artisan db:seed --class=DemoDataSeeder
 *
 * Everything here is fake and clearly labelled [DEMO]. The categories and "penalties"
 * are placeholders so the dashboard has something to show; they are NOT school policy.
 * Delete them (deactivate) and enter the official handbook rules before real use.
 */
class DemoDataSeeder extends Seeder
{
    public function run(ViolationWorkflowService $workflow): void
    {
        if (app()->isProduction()) {
            $this->command?->error('DemoDataSeeder refuses to run in production.');

            return;
        }

        $this->call(DatabaseSeeder::class);
        $admin = User::where('role', User::ROLE_ADMIN)->firstOrFail();

        // Officers (demo)
        $officers = collect(range(1, 3))->map(fn ($i) => User::firstOrCreate(
            ['email' => "officer{$i}@svms.test"],
            [
                'name' => "Demo Officer {$i}",
                'password' => 'Password!12345',
                'role' => User::ROLE_OFFICER,
                'position' => 'Demo Officer',
                'is_active' => true,
                'must_change_password' => false,
            ]
        ));

        // Courses, sections, students (fake)
        $courses = collect(['DEMO-CS', 'DEMO-BA', 'DEMO-ED'])->map(function ($code) {
            $course = Course::firstOrCreate(['code' => $code], ['name' => 'Demo Program '.$code, 'is_active' => true]);
            foreach (range(1, 4) as $year) {
                foreach (['A', 'B'] as $name) {
                    Section::firstOrCreate(['course_id' => $course->id, 'year_level' => $year, 'name' => $name]);
                }
            }

            return $course;
        });

        if (Student::count() < 40) {
            // course_id is overridden up-front so make() never creates stray Course rows.
            Student::factory()->count(40)->make(['course_id' => $courses->first()->id])->each(function (Student $student) use ($courses) {
                $course = $courses->random();
                $student->course_id = $course->id;
                $student->section_id = Section::where('course_id', $course->id)
                    ->where('year_level', $student->year_level)->inRandomOrder()->value('id');
                $student->save();
            });
        }

        // Placeholder actions + categories + rules (1st, 2nd, 3rd, 4th and succeeding)
        $actions = collect(range(1, 4))->map(fn ($n) => DisciplinaryAction::firstOrCreate(
            ['name' => "[DEMO] Action Level {$n}"],
            ['description' => 'Placeholder only. Replace with the official handbook penalty.', 'is_active' => true]
        ));

        $categories = collect(['A', 'B', 'C'])->map(function ($letter) use ($actions) {
            $category = ViolationCategory::firstOrCreate(
                ['name' => "[DEMO] Category {$letter}"],
                ['description' => 'Placeholder category. Not an official school violation.', 'is_active' => true]
            );
            foreach ($actions as $i => $action) {
                $number = $i + 1;
                OffenseRule::firstOrCreate(
                    ['violation_category_id' => $category->id, 'offense_number' => $number],
                    [
                        'is_succeeding' => $number === 4,
                        'description' => 'Placeholder rule.',
                        'disciplinary_action_id' => $action->id,
                        'is_active' => true,
                    ]
                );
            }

            return $category;
        });

        // Reports across the last ~6 months, pushed through the real workflow
        // (so offense numbers, snapshots, audit logs and notifications are genuine).
        $students = Student::all();
        foreach (range(1, 70) as $i) {
            $officer = $officers->random();
            $student = $students->random();
            $category = $categories->random();

            $record = $workflow->submit($officer, [
                'student_id' => $student->id,
                'violation_category_id' => $category->id,
                'incident_date' => now()->subDays(random_int(0, 180))->toDateString(),
                'incident_time' => sprintf('%02d:%02d', random_int(7, 17), random_int(0, 59)),
                'location' => collect(['Main Gate', 'Library', 'Canteen', 'Hallway', 'Room 101'])->random(),
                'description' => 'Demo incident description generated by the demo seeder.',
            ]);

            $roll = random_int(1, 100);
            try {
                if ($roll <= 55) {
                    $workflow->approve($admin, $record, 'Demo approval.');
                } elseif ($roll <= 70) {
                    $workflow->reject($admin, $record, 'Demo rejection: insufficient details.');
                } elseif ($roll <= 78) {
                    $workflow->returnForInfo($admin, $record, 'Demo: please add the exact time and location.');
                } // else: leave pending
            } catch (WorkflowException $e) {
                // ignore; leaves the record pending
            }
        }

        $this->command?->info('Demo data created. Demo logins: officer1@svms.test / Password!12345');
    }
}
